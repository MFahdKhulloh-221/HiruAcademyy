    public function run(): void
    {
        if (! app()->environment(['local', 'testing'])) {
            throw new \RuntimeException('Demo seeding requires local/testing environment.');
        }
        $connection = DB::connection();
        $config = $connection->getConfig();
        if (! in_array($config['host'] ?? null, ['localhost', '127.0.0.1'], true) || ! empty($config['url'])) {
            throw new \RuntimeException('Demo requires loopback PostgreSQL without a connection URL.');
        }
        DatabaseSafety::assertTarget(app()->environment('testing'));
        DB::transaction(function () {
            DB::select('SELECT pg_advisory_xact_lock(195051001)');
            $program = Program::where('code', 'n5')->where('status', 'active')->firstOrFail();
            $service = app(TryOutService::class);
            $matches = TryOut::where('program_id', $program->id)->whereIn('title', [self::TITLE, self::LEGACY_TITLE])->get();
            if ($matches->count() > 1) {
                throw new \RuntimeException('Multiple demo titles exist; manual review required.');
            }
            $demo = $matches->first();
            if ($demo) {
                $dataset = collect(self::questions())->keyBy(fn ($question) => $question['session'].':'.$question['sort_order']);
                foreach ($demo->questions as $existing) {
                    $expected = $dataset->get($existing->session.':'.$existing->sort_order);
                    if (! $expected || $existing->only(array_keys($expected)) != $expected) {
                        throw new \RuntimeException('Existing title contains non-demo or edited data; refusing to modify it.');
                    }
                }
            }
            if ($demo && ($demo->status !== 'draft' || TryOutAttempt::where('try_out_id', $demo->id)->exists())) {
                throw new \RuntimeException('Existing demo must remain an unused draft.');
            }
            $demo = $demo ? $service->save(['title' => self::TITLE], $demo) : $service->save(['program_id' => $program->id, 'title' => self::TITLE]);
            foreach (self::questions() as $question) {
                if (! $demo->questions()->where('session', $question['session'])->where('sort_order', $question['sort_order'])->exists()) {
                    $service->saveQuestion($demo, $question);
                }
            }
            $this->command?->info('Draft only; real matching N5 listening recordings required. Counts: '.json_encode($demo->questions()->select('session')->selectRaw('count(*) as count')->groupBy('session')->pluck('count', 'session')));
        });
    }
