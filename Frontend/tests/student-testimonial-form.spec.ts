import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";

test("student testimonial form uses account identity, draft previews and isolated submits", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (/hydration|hydrating/i.test(message.text())) errors.push(message.text()); });
  let historyFails = true;
  let submitFails = true;
  let submits = 0;
  const csrfToken = "fixture-csrf+token/=";
  let csrfReads = 0;
  let releaseSubmit: (() => void) | undefined;
  let pendingSubmit: Promise<void> | undefined;
  let lastBody: Record<string, unknown> = {};
  const user = { id: 987, name: "Siswa Fixture Nama Panjang", email: "fixture@example.test", whatsapp: "081234567890", role: "student", avatar: null, avatar_resolved_url: null, account_status: "active" };
  await page.route("http://localhost:8000/**", async route => {
    const url = new URL(route.request().url());
    if (url.pathname === "/api/me") return route.fulfill({ json: { data: user } });
    if (url.pathname === "/api/public/programs") return route.fulfill({ json: { data: [{ id: 1, code: "n4", name: "Program Akun N4", family: "jlpt" }] } });
    if (url.pathname === "/api/student/access") return route.fulfill({ json: { data: { learning: { n4: "full" }, replay_levels: ["n4"], source_grants: [{ plan_code: "sensei", program_code: "n4" }] } } });
    if (url.pathname === "/sanctum/csrf-cookie") {
      csrfReads++;
      await page.context().addCookies([{ name: "XSRF-TOKEN", value: encodeURIComponent(csrfToken), url: "http://localhost/", httpOnly: false, secure: false, sameSite: "Lax" }]);
      return route.fulfill({ status: 204 });
    }
    if (url.pathname === "/api/student/testimonial") {
      if (route.request().method() === "GET") return route.fulfill(historyFails ? { status: 500, json: { message: "fixture history failure" } } : { json: { data: null, context: "Program Akun N4" } });
      const multipart = route.request().method() === "POST";
      expect(["PUT", "POST"]).toContain(route.request().method());
      expect(route.request().headers()["x-xsrf-token"]).toBe(csrfToken);
      expect(await route.request().headerValue("cookie")).toContain(`XSRF-TOKEN=${encodeURIComponent(csrfToken)}`);
      submits++;
      if (multipart) {
        const request = route.request();
        const form = await new Response(new Uint8Array(request.postDataBuffer()!), { headers: { "Content-Type": request.headers()["content-type"] } }).formData();
        expect(form.get("_method")).toBe("PUT");
        const file = form.get("video_thumbnail") as File;
        expect(file.name).toBe("thumbnail.png");
        expect(file.size).toBeGreaterThan(0);
        lastBody = Object.fromEntries(form);
        delete lastBody._method;
        lastBody.video_thumbnail = "https://example.test/saved-thumbnail.png";
      } else lastBody = route.request().postDataJSON();
      if (submitFails) return route.fulfill({ status: 422, json: { errors: multipart ? { video_thumbnail: ["Thumbnail harus berupa PNG/JPG."] } : { quote: ["Komentar tidak valid."] } } });
      if (pendingSubmit) await pendingSubmit;
      return route.fulfill({ json: { data: { ...lastBody, id: 123, name: user.name, image: null, context: "Program Akun N4", moderation_status: "approved", published: true, show_on_testimonials: true, landing: false } } });
    }
    return route.fulfill({ json: { data: [] } });
  });
  await page.goto("/profile/testimoni?membership=sensei", { waitUntil: "domcontentloaded" });
  const kind = page.getByLabel("Jenis Testimoni", { exact: true });
  const comment = page.getByLabel("Komentar / Pengalaman Belajar", { exact: true });
  await expect(page).toHaveURL(/\/profile\/testimoni\?membership=sensei$/);
  await expect(page.getByRole("heading", { name: "Bagikan Pengalaman Belajarmu", exact: true })).toBeVisible();
  await expect(kind).toBeVisible();
  await kind.focus();
  await expect(kind).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(comment).toBeFocused();
  await expect(page.getByRole("tab")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Tambah Testimoni" })).toHaveCount(0);
  await expect(page.getByText(/Histori tertulis gagal dimuat/)).toContainText("HTTP 500");
  await expect(comment).toBeEditable();
  historyFails = false;
  await page.getByRole("button", { name: "Coba lagi", exact: true }).first().click();
  await expect(page.getByText("Belum ada testimoni yang dikirim.")).toBeVisible();
  const message = "Materi belajar jelas dan latihan membantu saya memahami bahasa Jepang. ".repeat(8);
  await comment.fill(message.slice(0, 480));
  await expect(page.locator(".testimonial-card blockquote")).toHaveText(message.slice(0, 480));
  await expect(page.locator(".testimonial-card header strong")).toHaveText(user.name);
  await expect(page.locator(".testimonial-card header small")).toHaveText("Program Akun N4");
  await expect(page.locator(".testimonial-avatar")).toContainText("SF");
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    const checkbox = page.getByRole("checkbox");
    const box = await checkbox.boundingBox();
    expect(box!.width).toBe(16);
    expect(box!.height).toBe(16);
    const text = await page.locator('label:has(input[type="checkbox"]) span').boundingBox();
    expect(box!.x).toBeGreaterThanOrEqual(text!.x + text!.width);
    const form = await page.locator("form").boundingBox();
    const preview = await page.getByRole("heading", { name: "Preview Testimoni", exact: true }).boundingBox();
    if (width === 1440) expect(preview!.x).toBeGreaterThan(form!.x + form!.width);
    else expect(preview!.y).toBeGreaterThan(form!.y + form!.height);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `C:/Users/Tulo/AppData/Local/Temp/opencode/student-testimonial-${width}.png`, fullPage: true });
  }
  await kind.selectOption("video");
  await page.getByLabel("Judul video (wajib)", { exact: true }).fill("Cerita belajar akun");
  await page.getByLabel("URL video", { exact: true }).fill("https://youtu.be/Q-YPfCfT2b0?si=1dQR_hTnFi2XLStg");
  await expect(page.getByRole("button", { name: "Tonton Cerita belajar akun" })).toBeVisible();
  await expect(page.getByLabel("URL thumbnail", { exact: true })).toHaveCount(0);
  await page.getByLabel("Thumbnail video", { exact: true }).setInputFiles({ name: "thumbnail.png", mimeType: "image/png", buffer: readFileSync("tests/fixtures/sample.png") });
  await expect(page.getByRole("button", { name: "Tonton Cerita belajar akun" }).locator("img")).toHaveAttribute("src", /^blob:/);
  await page.route("https://example.test/**", route => route.fulfill({ status: 404 }));
  await expect(page.getByRole("button", { name: "Tonton Cerita belajar akun" })).toBeVisible();
  await page.getByRole("button", { name: "Tonton Cerita belajar akun" }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.keyboard.press("Escape");
  await kind.selectOption("text");
  await expect(comment).toHaveValue(message.slice(0, 480));
  await expect(page.getByRole("button", { name: "Kirim Testimoni", exact: true })).toBeDisabled();
  await page.getByRole("checkbox").check();
  expect(submits).toBe(0);
  await page.getByRole("button", { name: "Kirim Testimoni", exact: true }).click();
  await expect(page.locator("form > p[role=alert]")).toContainText("HTTP 422");
  await expect(comment).toHaveValue(message.slice(0, 480));
  await expect(comment).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByText("Komentar tidak valid.", { exact: true })).toBeVisible();
  expect(csrfReads).toBe(1);
  await comment.fill(message.slice(0, 470));
  submitFails = false;
  pendingSubmit = new Promise<void>(resolve => { releaseSubmit = resolve; });
  await page.getByRole("button", { name: "Kirim Testimoni", exact: true }).click();
  await expect.poll(() => submits).toBe(2);
  await expect(page.getByRole("button", { name: /^Mengirim/ })).toBeDisabled();
  await page.locator("form").evaluate(form => { form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })); form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })); });
  expect(submits).toBe(2);
  releaseSubmit!();
  pendingSubmit = undefined;
  await expect(page.getByRole("status").filter({ hasText: "berhasil dikirim" })).toContainText("berhasil dikirim dan tayang");
  await expect(page.getByText("Tayang", { exact: true })).toBeVisible();
  expect(submits).toBe(2);
  expect(lastBody).not.toHaveProperty("name");
  expect(lastBody).not.toHaveProperty("context");
  expect(lastBody).not.toHaveProperty("user_id");
  await expect(comment).toBeDisabled();
  await kind.selectOption("video");
  await expect(page.getByLabel("Judul video (wajib)", { exact: true })).toHaveValue("Cerita belajar akun");
  await page.getByRole("checkbox").check();
  await page.getByLabel("Thumbnail video", { exact: true }).setInputFiles({ name: "renamed.jpg", mimeType: "image/jpeg", buffer: Buffer.from("not JPEG content") });
  await page.getByRole("button", { name: "Kirim Testimoni", exact: true }).click();
  await expect(page.getByText(/Isi thumbnail harus JPEG atau PNG/)).toBeVisible();
  expect(submits).toBe(2);
  await page.getByLabel("Thumbnail video", { exact: true }).setInputFiles({ name: "thumbnail.png", mimeType: "image/png", buffer: readFileSync("tests/fixtures/sample.png") });
  submitFails = true;
  await page.getByRole("button", { name: "Kirim Testimoni", exact: true }).click();
  await expect(page.getByText("Thumbnail harus berupa PNG/JPG.", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Thumbnail video", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByLabel("URL video", { exact: true })).toHaveValue("https://youtu.be/Q-YPfCfT2b0?si=1dQR_hTnFi2XLStg");
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.locator("form").screenshot({ path: `C:/Users/Tulo/AppData/Local/Temp/opencode/video-error-${width}.png` });
  }
  submitFails = false;
  await page.getByRole("button", { name: "Kirim Testimoni", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Testimoni video berhasil dipublikasikan" })).toBeVisible();
  expect(submits).toBe(4);
  expect(lastBody.video_url).toBe("https://youtu.be/Q-YPfCfT2b0?si=1dQR_hTnFi2XLStg");
  expect(errors).toEqual([]);
});
