import { expect, test } from "./canonical-fixture";

for (const resource of ["programs", "chapters"] as const) test(`R14 ${resource} positional order persists and errors stay open`, async ({ page }) => {
  const programs = [1, 2, 3, 4, 5].map((id, index) => ({ id, name: `Program ${id}`, code: `p${id}`, slug: `p${id}`, family: "jlpt", status: "draft", description: "", sort_order: [1, 2, 2, 4, 5][index] }));
  const chapters = [1, 2, 3, 4, 5, 6].map((id, index) => ({ id, program_id: id === 6 ? 2 : 1, title: `Chapter ${id}`, chapter_number: id, status: "draft", description: "", sort_order: [1, 2, 2, 4, 5, 8][index] }));
  let fail = false;
  let writes = 0;
  await page.route("**/api/admin/**", async route => {
    const path = new URL(route.request().url()).pathname;
    if (!/^\/api\/admin\/(programs|chapters)(\/\d+)?$/.test(path)) return route.fallback();
    const rows = path.includes("programs") ? programs : chapters;
    if (route.request().method() === "GET") return route.fulfill({ json: { data: [...rows].sort((a, b) => a.sort_order - b.sort_order || a.id - b.id) } });
    writes++;
    if (fail) return route.fulfill({ status: 503, json: { message: "Urutan gagal disimpan" } });
    const id = Number(path.split("/").at(-1));
    const body = route.request().postDataJSON();
    const row = rows.find(item => item.id === id)!;
    expect(body.sort_order).toBe(0);
    const group = rows.filter(item => !("program_id" in item) || item.program_id === 1).sort((a, b) => a.sort_order - b.sort_order || a.id - b.id).filter(item => item.id !== id);
    group.splice(body.sort_order, 0, row);
    group.forEach((item, index) => { item.sort_order = index; });
    return route.fulfill({ json: { data: row } });
  });
  await page.goto(`/admin/kurikulum-materi?tab=${resource === "programs" ? "Program" : "Kurikulum"}`);
  const table = page.getByRole("table", { name: resource === "programs" ? "Daftar Program" : "Chapter", exact: true });
  await expect(table).toBeVisible();
  const order = async () => table.locator("tbody tr").evaluateAll(rows => rows.map(row => row.querySelectorAll("td")[2]?.textContent));
  await expect.poll(order).toEqual(["1", "2", "3", "4", "5"]);
  const title = resource === "programs" ? "Program 5" : "Chapter 5";
  const row = table.getByRole("row").filter({ hasText: title });
  await row.getByRole("button", { name: resource === "programs" ? "Edit / Atur Urutan" : "Edit", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("spinbutton", { name: "Urutan", exact: true }).fill("1");
  fail = true;
  await dialog.getByRole("button", { name: "Simpan", exact: true }).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(dialog).toBeVisible();
  await expect(table.locator("tbody tr").last()).toContainText(title);
  fail = false;
  await dialog.getByRole("button", { name: "Simpan", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(table.locator("tbody tr").first()).toContainText(title);
  await expect.poll(order).toEqual(["1", "2", "3", "4", "5"]);
  await page.reload();
  await expect(table.locator("tbody tr").first()).toContainText(title);
  await expect.poll(order).toEqual(["1", "2", "3", "4", "5"]);
  expect(writes).toBe(2);
  expect(chapters.find(item => item.id === 6)?.sort_order).toBe(8);
});
