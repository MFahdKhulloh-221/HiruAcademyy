import { test, expect } from "./canonical-fixture";

test("builder image preview SEO draft publish schedule round trip", async ({ page, request }) => {
  let stored: Record<string, unknown> | null = null;
  const writes: Record<string, unknown>[] = [];
  const mediaRequests: string[] = [];
  let fail = false;
  await page.route("**/api/admin/blog-articles**", async route => {
    if (route.request().method() === "GET") { await route.fulfill({ json: { data: stored ? [stored] : [] } }); return; }
    const data = route.request().postDataJSON(); writes.push(data);
    if (fail) { await route.fulfill({ status: 500, json: { message: "Fixture failure" } }); return; }
    stored = { ...stored, ...data, id: 92 };
    await route.fulfill({ json: { data: stored } });
  });
  await page.route("**/api/admin/media", async route => {
    mediaRequests.push(route.request().method());
    expect(route.request().method()).toBe("POST");
    await route.fulfill({ json: { data: { path: "media/article.png", url: "http://127.0.0.1:3415/brand/hiru-atas.png", mime_type: "image/png" } } });
  });
  await page.goto("/admin/blog-seo/editor");
  await expect(page.getByLabel("Tanggal dan waktu terbit", { exact: true })).toHaveCount(0);
  const google = page.locator("details").filter({ has: page.getByText("Pengaturan Google (Opsional)", { exact: true }) });
  await expect(google).not.toHaveAttribute("open", "");
  await google.locator("summary").click();
  await page.getByLabel("Judul di Google (opsional)", { exact: true }).fill("");
  await page.getByLabel("Deskripsi di Google (opsional)", { exact: true }).fill("");
  await expect(page.getByPlaceholder("Otomatis mengikuti judul artikel", { exact: true })).toBeVisible();
  await google.locator("summary").click();
  await page.getByLabel("Judul artikel", { exact: true }).fill("Builder lengkap");
  await page.getByLabel("Ringkasan artikel", { exact: true }).fill("Ringkasan default SEO");
  await page.getByLabel("Isi artikel", { exact: true }).fill("Isi awal builder");
  await page.getByLabel("Kategori", { exact: true }).selectOption("Tips Belajar");
  await page.getByLabel("Penulis", { exact: true }).selectOption("Hiru Academy");
  await page.getByRole("button", { name: "Gambar", exact: true }).click();
  await page.getByLabel("Unggah Gambar Artikel", { exact: true }).setInputFiles({ name: "article.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aWWQAAAAASUVORK5CYII=", "base64") });
  await expect(page.getByRole("button", { name: "Ganti Gambar Artikel", exact: true })).toBeEnabled();
  await page.getByLabel("Teks alternatif", { exact: true }).fill("Logo contoh artikel");
  await page.getByLabel("Keterangan gambar", { exact: true }).fill("Keterangan contoh");
  await expect(page.getByRole("img", { name: "Logo contoh artikel", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Pratinjau Tulisan", exact: true }).click();
  const preview = page.getByRole("dialog", { name: "Pratinjau artikel", exact: true });
  await expect(preview.locator(".editorial-article-header h1")).toHaveText("Builder lengkap");
  await expect(preview.locator(".editorial-deck")).toHaveText("Ringkasan default SEO");
  await expect(preview.locator(".kicker")).toHaveText("Tips Belajar");
  await expect(preview.locator(".editorial-body")).toContainText("Isi awal builder");
  await page.screenshot({ path: "C:/Users/Tulo/AppData/Local/Temp/opencode/preview-desktop.png", fullPage: true });
  await expect(preview.getByRole("img", { name: "Logo contoh artikel" })).toBeVisible();
  await preview.getByRole("button", { name: "Mobile", exact: true }).click();
  await expect(preview.getByRole("button", { name: "Mobile", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.screenshot({ path: "C:/Users/Tulo/AppData/Local/Temp/opencode/preview-mobile.png", fullPage: true });
  expect(writes).toHaveLength(0);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Simpan Draft", exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/blog-seo$/);
  expect(stored).toMatchObject({ published: false, slug: "builder-lengkap", seo_title: "Builder lengkap", meta_description: "Ringkasan default SEO" });
  await page.getByRole("link", { name: "Builder lengkap", exact: true }).click();
  await expect(page.getByLabel("Teks alternatif", { exact: true })).toHaveValue("Logo contoh artikel");
  const savedBody = stored!.body;
  fail = true;
  await page.getByRole("button", { name: "Terbitkan Sekarang", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Permintaan belum berhasil" })).toBeVisible();
  expect(stored!.published).toBe(false);
  fail = false;
  await page.getByRole("button", { name: "Terbitkan Sekarang", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Tersimpan");
  expect(stored).toMatchObject({ published: true, body: savedBody });
  await page.getByLabel("Judul artikel", { exact: true }).fill("Judul published berubah");
  await page.getByRole("button", { name: "Simpan Perubahan", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Tersimpan");
  expect(stored).toMatchObject({ slug: "builder-lengkap", seo_title: "Builder lengkap", meta_description: "Ringkasan default SEO" });
  await request.post("http://127.0.0.1:3412/fixtures/articles", { data: [stored] });
  const response = await request.get("/blog/builder-lengkap");
  expect(response.status()).toBe(200);
  const html = await response.text();
  expect(html).toContain('alt="Logo contoh artikel"'); expect(html).toContain("Keterangan contoh");
  await page.getByRole("button", { name: "Kembalikan ke Draft", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Tersimpan"); expect(stored!.published).toBe(false);
  await page.getByRole("button", { name: "Jadwalkan untuk Nanti", exact: true }).click();
  await page.getByLabel("Tanggal dan waktu terbit", { exact: true }).fill("2099-01-02T10:30");
  await page.getByRole("button", { name: "Jadwalkan Artikel", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Tersimpan");
  expect(stored).toMatchObject({ published: true, published_at: "2099-01-02T03:30:00.000Z" });
  await page.getByRole("button", { name: "Hapus referensi gambar", exact: true }).click();
  await page.getByLabel("Unggah Gambar Artikel", { exact: true }).setInputFiles({ name: "replacement.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aWWQAAAAASUVORK5CYII=", "base64") });
  await expect(page.getByRole("img", { name: "Logo contoh artikel", exact: true })).toBeVisible();
  expect(mediaRequests).toEqual(["POST", "POST"]);
});
